-- 0054: Bank reconciliation (bank book vs bank statement).
--
--   * bank statement lines come from a feed (API pull, API push, CSV upload, or typed in) -> bank_transactions
--   * the "bank book" is every posted voucher line on that bank account's ledger (created in 0049)
--   * ADMIN-EDITABLE MATCH RULES (bank_recon_rules) decide how a statement line is paired with book entries:
--       auto_reconcile = link them, suggest = put a proposal in front of a human, exclude = keep the line out of the books
--   * a human can always override: match by hand, undo a match, exclude a line, include it again, book a missing entry
--   * a statement line that is already recorded in the books is MATCHED (never booked twice); a duplicate import is EXCLUDED
--   * order on import: 1) match against existing book entries  2) otherwise the Rule Book (0050) books it  3) otherwise Suspense draft
--
-- Nothing here edits a posted voucher. Reversals are new vouchers.

