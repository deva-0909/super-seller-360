-- ---------------------------------------------------------------- human overrides
create or replace function br_match_manual(p_txn uuid, p_line_ids uuid[], p_note text default null, p_allow_difference boolean default false) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare t bank_transactions%rowtype; v_ledger uuid; v_sum numeric; l uuid; v_row record; v_diff numeric;
begin
  if not has_bankcod_write() then raise exception 'Not authorized to reconcile'; end if;
  select * into t from bank_transactions where bank_txn_id = p_txn;
  if not found then raise exception 'Statement line not found'; end if;
  if p_line_ids is null or cardinality(p_line_ids) = 0 then raise exception 'Choose at least one book entry'; end if;
  if exists (select 1 from bank_recon_matches where bank_txn_id = p_txn and status = 'active' and method = 'rule_booked') then
    raise exception 'This line was booked from the statement by a rule. To change it, exclude the line and reverse the entry, or discard the draft.';
  end if;
  v_ledger := br_bank_ledger_of(t.bank_account_id);

  v_sum := 0;
  foreach l in array p_line_ids loop
    select vl.*, v.status as vstatus, v.voucher_no into v_row
      from voucher_lines vl join vouchers v on v.voucher_id = vl.voucher_id where vl.voucher_line_id = l;
    if not found then raise exception 'Book entry not found'; end if;
    if v_row.vstatus <> 'posted' then raise exception 'Voucher % is not posted yet', v_row.voucher_no; end if;
    if v_row.ledger_id <> v_ledger then raise exception 'Voucher % is not on this bank account''s ledger', v_row.voucher_no; end if;
    if (t.type = 'credit' and v_row.debit <= 0) or (t.type = 'debit' and v_row.credit <= 0) then
      raise exception 'Voucher % is on the wrong side (money %)', v_row.voucher_no, case when t.type = 'credit' then 'in' else 'out' end;
    end if;
    if exists (select 1 from bank_recon_matches m where m.voucher_line_id = l and m.status = 'active' and m.bank_txn_id <> p_txn) then
      raise exception 'Voucher % is already matched to another statement line - unmatch that one first', v_row.voucher_no;
    end if;
    v_sum := v_sum + case when t.type = 'credit' then v_row.debit else v_row.credit end;
  end loop;

  v_diff := t.amount - v_sum;
  if abs(v_diff) > 0.005 and not p_allow_difference then
    raise exception 'The chosen entries total % but the bank line is %. Tick "accept the difference" if that is intended.', v_sum, t.amount;
  end if;

  -- override: whatever was there before (rule match, old manual match, exclusion, rule draft) is replaced
  perform br_cancel_rule_draft(p_txn);
  perform br_unlink(p_txn);
  perform br_link(p_txn, p_line_ids, 'manual', null,
                  coalesce(p_note, '') || case when abs(v_diff) > 0.005 then ' [difference accepted: ' || v_diff || ']' else '' end);
  return jsonb_build_object('reconciled', true, 'difference', v_diff);
end $$;

create or replace function br_unmatch(p_txn uuid) returns void
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if not has_bankcod_write() then raise exception 'Not authorized to reconcile'; end if;
  if exists (select 1 from bank_recon_matches where bank_txn_id = p_txn and status = 'active' and method = 'rule_booked') then
    raise exception 'This line was booked from the statement by a rule, so it cannot simply be unmatched. Exclude it and reverse the entry instead.';
  end if;
  perform br_unlink(p_txn);
end $$;

create or replace function br_exclude_txn(p_txn uuid, p_reason text, p_note text default null, p_reverse boolean default false) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare t bank_transactions%rowtype; v_v vouchers%rowtype; v_rev uuid;
begin
  if not has_bankcod_write() then raise exception 'Not authorized to reconcile'; end if;
  if p_reason not in ('duplicate_import', 'own_transfer', 'not_business', 'other') then raise exception 'Unknown exclusion reason'; end if;
  select * into t from bank_transactions where bank_txn_id = p_txn;
  if not found then raise exception 'Statement line not found'; end if;

  -- a voucher the Rule Book made from this very line
  if t.matched_entity = 'journal_rule' and t.matched_reference_id is not null then
    select * into v_v from vouchers where voucher_id = t.matched_reference_id;
    if found and v_v.status = 'draft' then
      perform br_cancel_rule_draft(p_txn);
    elsif found and v_v.status = 'posted' then
      if not p_reverse then
        raise exception 'A rule already posted voucher % for this line. Excluding it means reversing that voucher - choose "also reverse the entry".', v_v.voucher_no;
      end if;
      v_rev := br_reverse_voucher(v_v.voucher_id, 'bank line excluded: ' || p_reason);
      update journal_rule_log set status = 'discarded', message = coalesce(message, '') || ' (reversed by ' || (select voucher_no from vouchers where voucher_id = v_rev) || ')'
       where voucher_id = v_v.voucher_id and status = 'posted';
      update bank_recon_matches set status = 'undone', undone_by = auth.uid(), undone_at = now()
       where bank_txn_id = p_txn and status = 'active';
      -- the original and its reversal cancel each other; neither belongs in reconciliation any more
      insert into bank_recon_book_exclusions (voucher_line_id, reason, excluded_by)
      select vl.voucher_line_id, 'Reversed: bank line excluded (' || p_reason || ')', auth.uid()
        from voucher_lines vl where vl.voucher_id in (v_v.voucher_id, v_rev) and vl.ledger_id = br_bank_ledger_of(t.bank_account_id)
      on conflict (voucher_line_id) do nothing;
    end if;
  end if;

  perform br_unlink(p_txn);
  update bank_recon_suggestions set status = 'withdrawn', decided_by = auth.uid(), decided_at = now() where bank_txn_id = p_txn and status = 'pending';
  update bank_transactions
     set recon_status = 'excluded', match_status = 'matched', matched_entity = 'excluded', matched_reference_id = null,
         excluded_reason = p_reason, excluded_by = auth.uid(), excluded_at = now(), recon_note = p_note
   where bank_txn_id = p_txn;
  return jsonb_build_object('excluded', true, 'reversal_voucher_id', v_rev);
end $$;

create or replace function br_include_txn(p_txn uuid) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if not has_bankcod_write() then raise exception 'Not authorized to reconcile'; end if;
  if not exists (select 1 from bank_transactions where bank_txn_id = p_txn and recon_status = 'excluded') then
    raise exception 'This line is not excluded';
  end if;
  update bank_transactions
     set recon_status = 'unreconciled', match_status = 'unmatched', matched_entity = null, matched_reference_id = null,
         excluded_reason = null, excluded_by = null, excluded_at = null, recon_note = null
   where bank_txn_id = p_txn;
  return jsonb_build_object('included', true, 'result', jr_process_bank_txn(p_txn));
end $$;

create or replace function br_accept_suggestion(p_suggestion uuid) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare s bank_recon_suggestions%rowtype;
begin
  if not has_bankcod_write() then raise exception 'Not authorized to reconcile'; end if;
  select * into s from bank_recon_suggestions where suggestion_id = p_suggestion and status = 'pending';
  if not found then raise exception 'This suggestion is no longer available'; end if;
  return br_match_manual(s.bank_txn_id, s.voucher_line_ids, 'Accepted suggestion from rule ' || coalesce(s.recon_rule_code, ''), true);
