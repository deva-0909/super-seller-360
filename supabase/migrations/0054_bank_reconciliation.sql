-- ---------------------------------------------------------------- helpers
create or replace function br_norm(p text) returns text
language sql immutable set search_path = public, pg_temp as $$
  select upper(regexp_replace(coalesce(p, ''), '[^A-Za-z0-9]', '', 'g'))
$$;

-- reference-like words that tie a book entry to a bank narration (voucher no, settlement id, order no, AWB-like words)
create or replace function br_tokens(p_voucher_no text, p_narr text, p_source_type text, p_source_id uuid) returns text[]
language plpgsql stable security definer set search_path = public, pg_temp as $$
declare v text[] := '{}';
begin
  v := array[br_norm(p_voucher_no)];
  v := v || coalesce((select array_agg(distinct br_norm(w)) from regexp_split_to_table(coalesce(p_narr, ''), '[^A-Za-z0-9\-/]+') w
                       where length(br_norm(w)) >= 5 and w ~ '[0-9]'), '{}');
  if p_source_type = 'settlement' then
    v := v || coalesce((select array[br_norm(external_settlement_id)] from settlements where settlement_id = p_source_id), '{}');
  elsif p_source_type = 'cod' then
    v := v || coalesce((select array[br_norm(o.external_order_id)] from cod_collections c join orders o on o.order_id = c.order_id where c.cod_id = p_source_id), '{}');
  end if;
  return array(select distinct k from unnest(v) k where length(k) >= 5);
end $$;

create or replace function br_bank_ledger_of(p_bank_account_id uuid) returns uuid
language sql stable security definer set search_path = public, pg_temp as $$
  select ledger_id from bank_accounts where bank_account_id = p_bank_account_id
$$;

-- Book entries that could pair with a statement line: posted lines on the bank ledger, right side, not already spoken for.
create or replace function br_candidates(p_txn_id uuid, p_window int, p_sources text[] default null, p_vtypes text[] default null)
returns table (voucher_line_id uuid, voucher_id uuid, voucher_no text, voucher_date date, amount numeric, narration text,
               source_type text, tokens text[], day_gap int)
language plpgsql stable security definer set search_path = public, pg_temp as $$
declare t bank_transactions%rowtype; v_ledger uuid;
begin
  select * into t from bank_transactions where bank_txn_id = p_txn_id;
  if not found then return; end if;
  v_ledger := br_bank_ledger_of(t.bank_account_id);
  if v_ledger is null then return; end if;
  return query
  select vl.voucher_line_id, v.voucher_id, v.voucher_no, v.voucher_date,
         (case when t.type = 'credit' then vl.debit else vl.credit end)::numeric,
         coalesce(vl.narration, v.narration), v.source_type,
         br_tokens(v.voucher_no, coalesce(vl.narration, v.narration), v.source_type, v.source_id),
         abs(v.voucher_date - t.txn_date)::int
    from voucher_lines vl
    join vouchers v on v.voucher_id = vl.voucher_id
    join voucher_types vt on vt.voucher_type_id = v.voucher_type_id
   where vl.ledger_id = v_ledger and v.status = 'posted'
     and ((t.type = 'credit' and vl.debit > 0) or (t.type = 'debit' and vl.credit > 0))
     and abs(v.voucher_date - t.txn_date) <= p_window
     and (p_sources is null or v.source_type = any (p_sources))
     and (p_vtypes  is null or vt.code = any (p_vtypes))
     and not exists (select 1 from bank_recon_matches m where m.voucher_line_id = vl.voucher_line_id and m.status = 'active')
     and not exists (select 1 from bank_recon_book_exclusions x where x.voucher_line_id = vl.voucher_line_id)
     and coalesce(v.source_type, '') <> 'reversal'
     and not exists (select 1 from vouchers rv where rv.source_type = 'reversal' and rv.source_id = v.voucher_id and rv.status = 'posted');
end $$;

-- Pair a statement line with book entries.
create or replace function br_link(p_txn uuid, p_line_ids uuid[], p_method text, p_rule_code text, p_note text) returns void
language plpgsql security definer set search_path = public, pg_temp as $$
declare t bank_transactions%rowtype; l uuid; v_amt numeric; v_vid uuid;
begin
  if p_method <> 'rule_booked' then perform br_cancel_rule_draft(p_txn); end if;
  select * into t from bank_transactions where bank_txn_id = p_txn;
  foreach l in array p_line_ids loop
    select (case when t.type = 'credit' then vl.debit else vl.credit end), vl.voucher_id into v_amt, v_vid
      from voucher_lines vl where vl.voucher_line_id = l;
    insert into bank_recon_matches (bank_txn_id, voucher_line_id, amount, method, recon_rule_code, note, matched_by)
    values (p_txn, l, v_amt, p_method, p_rule_code, p_note, auth.uid());
  end loop;
  select vl.voucher_id into v_vid from voucher_lines vl where vl.voucher_line_id = p_line_ids[1];
  update bank_transactions
     set recon_status = 'reconciled', recon_note = coalesce(p_note, recon_note),
         match_status = 'matched',
         matched_entity = coalesce(matched_entity, case when p_method = 'rule_booked' then 'journal_rule' else 'book_entry' end),
         matched_reference_id = coalesce(matched_reference_id, v_vid),
         excluded_reason = null, excluded_by = null, excluded_at = null
   where bank_txn_id = p_txn;
  update bank_recon_suggestions set status = case when voucher_line_ids @> p_line_ids and p_line_ids @> voucher_line_ids then 'accepted' else 'withdrawn' end,
         decided_by = auth.uid(), decided_at = now()
   where bank_txn_id = p_txn and status = 'pending';
end $$;

-- Link the bank leg of a voucher that was created FROM this statement line by the Rule Book.
create or replace function br_link_rule_voucher(p_txn uuid, p_voucher uuid) returns void
language plpgsql security definer set search_path = public, pg_temp as $$
declare t bank_transactions%rowtype; v_ledger uuid; v_ids uuid[];
begin
  select * into t from bank_transactions where bank_txn_id = p_txn;
  if not found then return; end if;
  if not exists (select 1 from vouchers where voucher_id = p_voucher and status = 'posted') then return; end if;
  v_ledger := br_bank_ledger_of(t.bank_account_id);
  select array_agg(vl.voucher_line_id) into v_ids from voucher_lines vl
   where vl.voucher_id = p_voucher and vl.ledger_id = v_ledger
     and ((t.type = 'credit' and vl.debit > 0) or (t.type = 'debit' and vl.credit > 0))
     and not exists (select 1 from bank_recon_matches m where m.voucher_line_id = vl.voucher_line_id and m.status = 'active');
  if v_ids is null then return; end if;
  perform br_link(p_txn, v_ids, 'rule_booked', null, 'Booked from this bank line by a rule');
end $$;

-- Undo active matches (statement line goes back to unreconciled).
create or replace function br_unlink(p_txn uuid) returns void
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  update bank_recon_matches set status = 'undone', undone_by = auth.uid(), undone_at = now() where bank_txn_id = p_txn and status = 'active';
  update bank_transactions
     set recon_status = 'unreconciled',
         match_status = case when matched_entity in ('book_entry','excluded') then 'unmatched' else match_status end,
         matched_reference_id = case when matched_entity in ('book_entry','excluded') then null else matched_reference_id end,
         matched_entity = case when matched_entity in ('book_entry','excluded') then null else matched_entity end,
         excluded_reason = null, excluded_by = null, excluded_at = null
   where bank_txn_id = p_txn;
end $$;

-- A draft entry the Rule Book made from this line is thrown away when a human decides the line another way.
create or replace function br_cancel_rule_draft(p_txn uuid) returns void
language plpgsql security definer set search_path = public, pg_temp as $$
declare t bank_transactions%rowtype;
begin
  select * into t from bank_transactions where bank_txn_id = p_txn;
  if t.matched_entity = 'journal_rule' and t.matched_reference_id is not null
     and exists (select 1 from vouchers where voucher_id = t.matched_reference_id and status = 'draft') then
    update vouchers set status = 'cancelled' where voucher_id = t.matched_reference_id;
    update journal_rule_log set status = 'discarded' where voucher_id = t.matched_reference_id and status = 'draft';
    update credit_notes set status = 'cancelled' where voucher_id = t.matched_reference_id and status = 'draft';
    update bank_transactions set matched_entity = null, matched_reference_id = null, match_status = 'unmatched' where bank_txn_id = p_txn;
  end if;
end $$;

-- A reversing journal for a posted voucher (posted vouchers are never edited).
create or replace function br_reverse_voucher(p_voucher uuid, p_reason text) returns uuid
language plpgsql security definer set search_path = public, pg_temp as $$
declare v vouchers%rowtype; v_new uuid; v_date date; v_period uuid; v_vt uuid; v_prefix text; v_no text;
begin
  select * into v from vouchers where voucher_id = p_voucher;
  if not found or v.status <> 'posted' then raise exception 'Only a posted voucher can be reversed'; end if;
  v_date := current_date;
  select accounting_period_id into v_period from accounting_periods where v_date between start_date and end_date and status = 'open' limit 1;
  if v_period is null then
    v_date := v.voucher_date;
    select accounting_period_id into v_period from accounting_periods where v_date between start_date and end_date and status = 'open' limit 1;
  end if;
  if v_period is null then raise exception 'No open accounting period to post the reversal in'; end if;
  select voucher_type_id, numbering_prefix into v_vt, v_prefix from voucher_types where code = 'JOURNAL';
  v_no := v_prefix || '-' || to_char(v_date, 'YYMM') || '-' || lpad(nextval('journal_voucher_seq')::text, 6, '0');
  insert into vouchers (voucher_type_id, voucher_no, voucher_date, accounting_period_id, status, source_type, source_id, narration, total_debit, total_credit, created_by)
  values (v_vt, v_no, v_date, v_period, 'draft', 'reversal', p_voucher, 'Reversal of ' || v.voucher_no || ' - ' || coalesce(p_reason, ''), v.total_debit, v.total_credit, auth.uid())
  returning voucher_id into v_new;
  insert into voucher_lines (voucher_id, ledger_id, debit, credit, narration)
  select v_new, ledger_id, credit, debit, 'Reversal' from voucher_lines where voucher_id = p_voucher;
  update vouchers set status = 'posted' where voucher_id = v_new;
  return v_new;
end $$;

-- ---------------------------------------------------------------- the matching engine
create or replace function br_apply_rules_to_txn(p_txn uuid) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  t bank_transactions%rowtype; r bank_recon_rules%rowtype;
  v_desc text; v_norm text; v_tol numeric; v_hits jsonb; v_n int; v_top int; v_same int; v_ids uuid[];
  c record; n int; mask int; i int; cnt int; v_sum numeric; v_sets jsonb; v_set uuid[]; v_k int;
  v_amts numeric[]; v_lids uuid[]; v_scores int[]; v_made int;
begin
  select * into t from bank_transactions where bank_txn_id = p_txn;
  if not found then return jsonb_build_object('skipped', 'line not found'); end if;
  if t.recon_status in ('reconciled', 'excluded') then return jsonb_build_object('skipped', 'already ' || t.recon_status); end if;
  v_desc := coalesce(t.reference, '');
  v_norm := br_norm(v_desc);

  -- start clean: old pending proposals are recomputed
  update bank_recon_suggestions set status = 'withdrawn' where bank_txn_id = p_txn and status = 'pending';

  for r in select * from bank_recon_rules
            where status = 'active' and (bank_account_id is null or bank_account_id = t.bank_account_id)
              and (direction = 'any' or direction = t.type)
            order by priority, rule_code loop

    if r.keyword_operator is not null and not jr_cond_ok(jsonb_build_object('d', v_desc), 'd', r.keyword_operator, r.keyword_value) then
      continue;
    end if;

    if r.action = 'exclude' then
      perform br_cancel_rule_draft(p_txn);
      update bank_transactions set recon_status = 'excluded', match_status = 'matched', matched_entity = 'excluded',
             excluded_reason = coalesce(r.exclude_reason, 'other'), excluded_at = now(),
             recon_note = 'Excluded by rule ' || r.rule_code || ' - ' || r.name
       where bank_txn_id = p_txn;
      return jsonb_build_object('excluded', r.rule_code);
    end if;

    v_tol := greatest(r.amount_tolerance, round(t.amount * r.amount_tolerance_pct / 100, 2));

    if r.match_type = 'one_to_one' then
      select jsonb_agg(jsonb_build_object('id', x.voucher_line_id, 'score', x.score) order by x.score desc, x.day_gap, x.voucher_date)
        into v_hits
        from (select c2.voucher_line_id, c2.day_gap, c2.voucher_date,
                     (case when exists (select 1 from unnest(c2.tokens) k where position(k in v_norm) > 0) then 50 else 0 end
                      + case when c2.amount = t.amount then 30 else 0 end + greatest(20 - c2.day_gap * 3, 0)) as score,
                     exists (select 1 from unnest(c2.tokens) k where position(k in v_norm) > 0) as ref_hit
                from br_candidates(p_txn, r.date_window_days, r.book_source_types, r.book_voucher_types) c2
               where abs(c2.amount - t.amount) <= v_tol) x
       where (r.reference_mode <> 'required' or x.ref_hit)
         and not exists (select 1 from bank_recon_suggestions s where s.bank_txn_id = p_txn and s.status = 'rejected'
                            and s.voucher_line_ids = array[x.voucher_line_id]);
      if v_hits is null then continue; end if;
      v_n := jsonb_array_length(v_hits);
      v_top := (v_hits -> 0 ->> 'score')::int;
      select count(*) into v_same from jsonb_array_elements(v_hits) e where (e ->> 'score')::int = v_top;
      if r.action = 'auto_reconcile' and v_same = 1 then
        perform br_link(p_txn, array[(v_hits -> 0 ->> 'id')::uuid], 'auto_rule', r.rule_code,
                        'Matched by rule ' || r.rule_code);
        return jsonb_build_object('reconciled', r.rule_code, 'lines', 1);
      end if;
      v_made := 0;
      for i in 0 .. least(v_n, 5) - 1 loop
        insert into bank_recon_suggestions (bank_txn_id, voucher_line_ids, recon_rule_code, score)
        values (p_txn, array[(v_hits -> i ->> 'id')::uuid], r.rule_code, (v_hits -> i ->> 'score')::int);
        v_made := v_made + 1;
      end loop;
      update bank_transactions set recon_status = 'suggested' where bank_txn_id = p_txn;
      return jsonb_build_object('suggested', r.rule_code, 'count', v_made);

    else
      -- several book entries together equal one statement line (e.g. two settlements credited as one bank entry)
      v_lids := '{}'; v_amts := '{}'; v_scores := '{}';
      for c in select c2.voucher_line_id, c2.amount,
                      (case when exists (select 1 from unnest(c2.tokens) k where position(k in v_norm) > 0) then 1 else 0 end) as hit
                 from br_candidates(p_txn, r.date_window_days, r.book_source_types, r.book_voucher_types) c2
                where c2.amount > 0 and c2.amount <= t.amount + v_tol
                order by hit desc, c2.day_gap, c2.voucher_date limit 12 loop
        v_lids := v_lids || c.voucher_line_id; v_amts := v_amts || c.amount;
      end loop;
      n := coalesce(array_length(v_lids, 1), 0);
      if n < 2 then continue; end if;
      v_sets := '[]'::jsonb;
      for mask in 1 .. (1 << n) - 1 loop
        cnt := 0; v_sum := 0;
        for i in 1 .. n loop
          if (mask & (1 << (i - 1))) <> 0 then cnt := cnt + 1; v_sum := v_sum + v_amts[i]; end if;
        end loop;
        if cnt between 2 and 5 and abs(v_sum - t.amount) <= v_tol then
          v_set := '{}';
          for i in 1 .. n loop
            if (mask & (1 << (i - 1))) <> 0 then v_set := v_set || v_lids[i]; end if;
          end loop;
          if not exists (select 1 from bank_recon_suggestions s where s.bank_txn_id = p_txn and s.status = 'rejected' and s.voucher_line_ids @> v_set and v_set @> s.voucher_line_ids) then
            v_sets := v_sets || jsonb_build_array(to_jsonb(v_set));
          end if;
          exit when jsonb_array_length(v_sets) >= 3;
        end if;
      end loop;
      if jsonb_array_length(v_sets) = 0 then continue; end if;
      if r.action = 'auto_reconcile' and jsonb_array_length(v_sets) = 1 then
        select array_agg(x::uuid) into v_set from jsonb_array_elements_text(v_sets -> 0) x;
        perform br_link(p_txn, v_set, 'auto_rule', r.rule_code, 'Several entries matched by rule ' || r.rule_code);
        return jsonb_build_object('reconciled', r.rule_code, 'lines', cardinality(v_set));
      end if;
      for i in 0 .. jsonb_array_length(v_sets) - 1 loop
        select array_agg(x::uuid) into v_set from jsonb_array_elements_text(v_sets -> i) x;
        insert into bank_recon_suggestions (bank_txn_id, voucher_line_ids, recon_rule_code, score) values (p_txn, v_set, r.rule_code, 40);
      end loop;
      update bank_transactions set recon_status = 'suggested' where bank_txn_id = p_txn;
      return jsonb_build_object('suggested', r.rule_code, 'count', jsonb_array_length(v_sets));
    end if;
  end loop;

  update bank_transactions set recon_status = 'unreconciled' where bank_txn_id = p_txn and recon_status = 'suggested';
  return jsonb_build_object('no_match', true);
end $$;

-- ---------------------------------------------------------------- Rule Book hook: reconcile first, book only what is left
create or replace function jr_process_bank_txn(p_txn_id uuid) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  t bank_transactions%rowtype; v_ctx jsonb; v_res jsonb; v_item jsonb; v_rec jsonb;
begin
  select * into t from bank_transactions where bank_txn_id = p_txn_id;
  if not found or t.match_status <> 'unmatched' then return jsonb_build_object('skipped', 'not an unmatched line'); end if;
  if t.recon_status in ('reconciled', 'excluded') then return jsonb_build_object('skipped', 'already ' || t.recon_status); end if;

  -- 1. is it already in the books? (or should it be kept out of them?)
  v_rec := br_apply_rules_to_txn(p_txn_id);
  select * into t from bank_transactions where bank_txn_id = p_txn_id;
  if t.recon_status in ('reconciled', 'excluded', 'suggested') then
    return jsonb_build_object('reconciliation', v_rec);
  end if;

  -- 2. not in the books: let the Rule Book book it
  v_ctx := jsonb_build_object(
    'description', coalesce(t.reference, ''), 'amount', t.amount, 'direction', t.type, 'date', t.txn_date,
    'bank_account_id', t.bank_account_id,
    'bank_account', (select bank_name from bank_accounts where bank_account_id = t.bank_account_id));
  v_res := jr_fire('bank.' || t.type, 'bank_txn', t.bank_txn_id, v_ctx, 'bank:' || t.bank_txn_id);
  for v_item in select * from jsonb_array_elements(coalesce(v_res -> 'results', '[]'::jsonb)) loop
    update bank_transactions
       set matched_entity = 'journal_rule', matched_reference_id = (v_item ->> 'voucher_id')::uuid,
           match_status = case when v_item ->> 'status' = 'posted' then 'matched' else 'partial' end
     where bank_txn_id = p_txn_id;
    if v_item ->> 'status' = 'posted' then
      perform br_link_rule_voucher(p_txn_id, (v_item ->> 'voucher_id')::uuid);
    end if;
  end loop;
  return v_res;
end $$;

-- approving / discarding a rule draft now keeps reconciliation in step
create or replace function approve_rule_voucher(p_voucher_id uuid) returns void
language plpgsql security definer set search_path = public, pg_temp as $$
declare bt record;
begin
  if not has_accounting_write() then raise exception 'Not authorized to approve vouchers'; end if;
  if not exists (select 1 from vouchers where voucher_id = p_voucher_id and status = 'draft') then
    raise exception 'Only a draft voucher can be approved';
  end if;
  if exists (select 1 from bank_transactions where matched_entity = 'journal_rule' and matched_reference_id = p_voucher_id and recon_status = 'suggested') then
    raise exception 'A reconciliation suggestion is still open for this bank line - accept or reject it first, so the entry is not booked twice';
  end if;
  update vouchers set status = 'posted', approved_by = auth.uid() where voucher_id = p_voucher_id;
  update journal_rule_log set status = 'posted' where voucher_id = p_voucher_id and status = 'draft';
  update credit_notes set status = 'posted' where voucher_id = p_voucher_id and status = 'draft';
  update bank_transactions set match_status = 'matched'
   where matched_entity = 'journal_rule' and matched_reference_id = p_voucher_id;
  for bt in select bank_txn_id from bank_transactions where matched_entity = 'journal_rule' and matched_reference_id = p_voucher_id loop
    perform br_link_rule_voucher(bt.bank_txn_id, p_voucher_id);
  end loop;
end $$;

-- ---------------------------------------------------------------- statement ingestion (API / CSV / typed)
create or replace function br_ingest(p_bank_account_id uuid, p_lines jsonb, p_source text) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  ln jsonb; v_date date; v_amt numeric; v_type text; v_desc text; v_ext text; v_bal numeric; v_val date; v_hash text;
  v_ins int := 0; v_dup int := 0; v_bad int := 0; v_errs jsonb := '[]'::jsonb; v_idx int := 0; v_id uuid; v_ids uuid[] := '{}';
  v_seen jsonb := '{}'::jsonb; v_occ int; v_key text;
  v_rec int; v_sug int; v_exc int; v_booked int; v_open int; v_drafts int;
begin
  if not exists (select 1 from bank_accounts where bank_account_id = p_bank_account_id) then raise exception 'Unknown bank account'; end if;
  if jsonb_typeof(p_lines) <> 'array' then raise exception 'Expected a list of statement lines'; end if;
  if jsonb_array_length(p_lines) > 5000 then raise exception 'Send at most 5000 lines at a time'; end if;

  for ln in select * from jsonb_array_elements(p_lines) loop
    v_idx := v_idx + 1;
    begin
      v_date := coalesce(nullif(ln ->> 'date', ''), nullif(ln ->> 'txn_date', ''))::date;
      v_val  := nullif(ln ->> 'value_date', '')::date;
      v_amt  := nullif(replace(coalesce(ln ->> 'amount', ''), ',', ''), '')::numeric;
      v_type := lower(coalesce(ln ->> 'type', ''));
      if v_amt is null and ln ? 'debit' and coalesce(nullif(replace(ln ->> 'debit', ',', ''), '')::numeric, 0) > 0 then
        v_amt := replace(ln ->> 'debit', ',', '')::numeric; v_type := 'debit';
      elsif v_amt is null and ln ? 'credit' and coalesce(nullif(replace(ln ->> 'credit', ',', ''), '')::numeric, 0) > 0 then
        v_amt := replace(ln ->> 'credit', ',', '')::numeric; v_type := 'credit';
      end if;
      if v_amt is null then raise exception 'no amount'; end if;
      if v_type not in ('credit', 'debit') then v_type := case when v_amt < 0 then 'debit' else 'credit' end; end if;
      v_amt := abs(v_amt);
      if v_date is null then raise exception 'no date'; end if;
      if v_amt < 0.005 then raise exception 'zero amount'; end if;
      v_desc := btrim(coalesce(ln ->> 'description', ln ->> 'reference', ln ->> 'narration', ''));
      v_ext  := nullif(btrim(coalesce(ln ->> 'external_id', ln ->> 'txn_id', '')), '');
      v_bal  := nullif(replace(coalesce(ln ->> 'balance', ''), ',', ''), '')::numeric;
      if v_ext is not null then
        v_hash := null;
      else
        v_key := concat_ws('|', p_bank_account_id, v_date, v_type, v_amt, upper(v_desc), coalesce(v_bal::text, ''));
        v_occ := coalesce((v_seen ->> v_key)::int, 0) + 1;
        v_seen := v_seen || jsonb_build_object(v_key, v_occ);
        v_hash := md5(v_key || '|' || v_occ);
      end if;
      insert into bank_transactions (bank_account_id, txn_date, reference, amount, type, external_txn_id, value_date, balance, source, line_hash, raw)
      values (p_bank_account_id, v_date, nullif(v_desc, ''), v_amt, v_type, v_ext, v_val, v_bal, p_source, v_hash, ln)
      on conflict do nothing
      returning bank_txn_id into v_id;
      if v_id is null then v_dup := v_dup + 1; else v_ins := v_ins + 1; v_ids := v_ids || v_id; end if;
      v_id := null;
    exception when others then
      v_bad := v_bad + 1;
      if jsonb_array_length(v_errs) < 20 then v_errs := v_errs || jsonb_build_array(jsonb_build_object('row', v_idx, 'problem', sqlerrm)); end if;
    end;
  end loop;

  select count(*) filter (where matched_entity = 'journal_rule' and match_status = 'partial') into v_drafts
    from bank_transactions where bank_txn_id = any (v_ids);
  select count(*) filter (where recon_status = 'reconciled' and match_status = 'matched' and matched_entity = 'book_entry'),
         count(*) filter (where recon_status = 'suggested'),
         count(*) filter (where recon_status = 'excluded'),
         count(*) filter (where matched_entity = 'journal_rule' and match_status = 'matched'),
         count(*) filter (where recon_status = 'unreconciled' and matched_entity is distinct from 'journal_rule')
    into v_rec, v_sug, v_exc, v_booked, v_open
    from bank_transactions where bank_txn_id = any (v_ids);

  insert into bank_feeds (bank_account_id, provider, last_synced_at, last_status, last_message)
  values (p_bank_account_id, case when p_source = 'api' then 'api_push' when p_source = 'csv' then 'csv' else 'manual' end, now(),
          case when v_bad > 0 then 'partial' else 'ok' end, v_ins || ' new, ' || v_dup || ' already imported, ' || v_bad || ' rejected')
  on conflict (bank_account_id) do update
    set last_synced_at = now(), last_status = excluded.last_status, last_message = excluded.last_message;

  return jsonb_build_object('received', v_idx, 'imported', v_ins, 'duplicates_skipped', v_dup, 'rejected', v_bad, 'problems', v_errs,
                            'matched_to_books', v_rec, 'suggested', v_sug, 'excluded', v_exc, 'booked_by_rules', v_booked, 'sent_for_review', v_drafts, 'needs_attention', v_open);
end $$;

