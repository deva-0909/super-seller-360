-- the reconciliation statement: how the bank book and the bank statement tie together
create or replace function bank_recon_summary(p_bank_account_id uuid) returns jsonb
language plpgsql stable security definer set search_path = public, pg_temp as $$
declare
  v_ledger uuid; v_lg ledgers%rowtype; v_feed bank_feeds%rowtype;
  v_open_b numeric := 0; v_book numeric; v_open_s numeric := 0; v_stmt numeric;
  v_bo_cr numeric; v_bo_db numeric; v_set_cr numeric; v_set_db numeric; v_bk_in numeric; v_bk_out numeric; v_bx_in numeric; v_bx_out numeric;
  v_diffs numeric; v_expected numeric; v_reported numeric; v_reported_date date; v_computed_at_reported numeric; v_seq bigint;
  v_counts jsonb;
begin
  if not has_bankcod_view() then raise exception 'Not authorized'; end if;
  v_ledger := br_bank_ledger_of(p_bank_account_id);
  if v_ledger is null then raise exception 'This bank account has no ledger'; end if;
  select * into v_lg from ledgers where ledger_id = v_ledger;
  select * into v_feed from bank_feeds where bank_account_id = p_bank_account_id;
  v_open_b := case when v_lg.opening_balance_type = 'credit' then -v_lg.opening_balance else v_lg.opening_balance end;
  v_open_s := coalesce(v_feed.statement_opening_balance, 0);

  select v_open_b + coalesce(sum(vl.debit - vl.credit), 0) into v_book
    from voucher_lines vl join vouchers v on v.voucher_id = vl.voucher_id where vl.ledger_id = v_ledger and v.status = 'posted';

  select v_open_s + coalesce(sum(case when type = 'credit' then amount else -amount end), 0) into v_stmt
    from bank_transactions where bank_account_id = p_bank_account_id and coalesce(excluded_reason, '') <> 'duplicate_import';

  select coalesce(sum(amount) filter (where type = 'credit'), 0), coalesce(sum(amount) filter (where type = 'debit'), 0) into v_bo_cr, v_bo_db
    from bank_transactions where bank_account_id = p_bank_account_id and recon_status in ('unreconciled', 'suggested');
  select coalesce(sum(amount) filter (where type = 'credit'), 0), coalesce(sum(amount) filter (where type = 'debit'), 0) into v_set_cr, v_set_db
    from bank_transactions where bank_account_id = p_bank_account_id and recon_status = 'excluded' and coalesce(excluded_reason, '') <> 'duplicate_import';

  select coalesce(sum(vl.debit) filter (where x.voucher_line_id is null), 0), coalesce(sum(vl.credit) filter (where x.voucher_line_id is null), 0),
         coalesce(sum(vl.debit) filter (where x.voucher_line_id is not null), 0), coalesce(sum(vl.credit) filter (where x.voucher_line_id is not null), 0)
    into v_bk_in, v_bk_out, v_bx_in, v_bx_out
    from voucher_lines vl join vouchers v on v.voucher_id = vl.voucher_id
    left join bank_recon_book_exclusions x on x.voucher_line_id = vl.voucher_line_id
   where vl.ledger_id = v_ledger and v.status = 'posted'
     and not exists (select 1 from bank_recon_matches m where m.voucher_line_id = vl.voucher_line_id and m.status = 'active');

  -- differences the user chose to accept on matched lines (bank amount vs book amount)
  select coalesce(sum((case when b.type = 'credit' then 1 else -1 end) * (b.amount - coalesce(ms.amt, 0))), 0) into v_diffs
    from bank_transactions b
    left join (select bank_txn_id, sum(amount) amt from bank_recon_matches where status = 'active' group by bank_txn_id) ms on ms.bank_txn_id = b.bank_txn_id
   where b.bank_account_id = p_bank_account_id and b.recon_status = 'reconciled';

  v_expected := v_book + v_bo_cr - v_bo_db + v_set_cr - v_set_db - v_bk_in + v_bk_out - v_bx_in + v_bx_out + v_diffs + (v_open_s - v_open_b);

  -- the bank's own running balance on the last imported line vs what the imported lines add up to (spots missing lines in the feed)
  select balance, txn_date, import_seq into v_reported, v_reported_date, v_seq from bank_transactions
   where bank_account_id = p_bank_account_id and balance is not null order by import_seq desc limit 1;
  if v_reported is not null then
    select v_open_s + coalesce(sum(case when type = 'credit' then amount else -amount end), 0) into v_computed_at_reported
      from bank_transactions where bank_account_id = p_bank_account_id and import_seq <= v_seq and coalesce(excluded_reason, '') <> 'duplicate_import';
  end if;

  select jsonb_build_object(
      'statement_lines', count(*), 'reconciled', count(*) filter (where recon_status = 'reconciled'),
      'suggested', count(*) filter (where recon_status = 'suggested'), 'unreconciled', count(*) filter (where recon_status = 'unreconciled'),
      'excluded', count(*) filter (where recon_status = 'excluded'))
    into v_counts from bank_transactions where bank_account_id = p_bank_account_id;

  return jsonb_build_object(
    'ledger', v_lg.name,
    'book_balance', v_book,
    'statement_balance', v_stmt,
    'difference', v_stmt - v_book,
    'in_bank_not_in_books', jsonb_build_object('money_in', v_bo_cr, 'money_out', v_bo_db),
    'set_aside_by_you', jsonb_build_object('money_in', v_set_cr, 'money_out', v_set_db),
    'in_books_not_in_bank', jsonb_build_object('money_in', v_bk_in, 'money_out', v_bk_out),
    'books_entries_set_aside', jsonb_build_object('money_in', v_bx_in, 'money_out', v_bx_out),
    'accepted_differences', v_diffs,
    'opening_gap', v_open_s - v_open_b,
    'unexplained', round(v_stmt - v_expected, 2),
    'bank_reported_balance', v_reported, 'bank_reported_on', v_reported_date,
    'feed_gap', case when v_reported is null then null else round(v_reported - v_computed_at_reported, 2) end,
    'counts', v_counts);
end $$;

-- ---------------------------------------------------------------- admin: match rules + feed settings
create or replace function save_bank_recon_rule(p_rule jsonb) returns uuid
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_id uuid := nullif(p_rule ->> 'recon_rule_id', '')::uuid; v_action text := p_rule ->> 'action'; v_type text := coalesce(p_rule ->> 'match_type', 'one_to_one');
  v_src text[]; v_vt text[]; v_code text;
begin
  if not has_rulebook_edit() then raise exception 'Only a Super Admin or Finance Manager can change the matching rules'; end if;
  if coalesce(btrim(p_rule ->> 'name'), '') = '' then raise exception 'Rule name is required'; end if;
  if v_action not in ('auto_reconcile', 'suggest', 'exclude') then raise exception 'Choose what the rule should do'; end if;
  if v_action = 'exclude' and (coalesce(btrim(p_rule ->> 'keyword_value'), '') = '' or coalesce(p_rule ->> 'keyword_operator', '') = '') then
    raise exception 'An exclude rule must say which words in the bank narration to look for';
  end if;
  if v_type not in ('one_to_one', 'sum_of_entries') then raise exception 'Unknown match type'; end if;
  if jsonb_typeof(p_rule -> 'book_source_types') = 'array' then
    select nullif(array_agg(x), '{}') into v_src from jsonb_array_elements_text(p_rule -> 'book_source_types') x where btrim(x) <> '';
  end if;
  if jsonb_typeof(p_rule -> 'book_voucher_types') = 'array' then
    select nullif(array_agg(x), '{}') into v_vt from jsonb_array_elements_text(p_rule -> 'book_voucher_types') x where btrim(x) <> '';
  end if;

  if v_id is null then
    v_code := 'RC-C-' || lpad(nextval('journal_voucher_seq')::text, 4, '0');
    insert into bank_recon_rules (rule_code, name, description, priority, status, bank_account_id, direction, action, match_type, amount_tolerance, amount_tolerance_pct,
        date_window_days, reference_mode, keyword_operator, keyword_value, book_source_types, book_voucher_types, exclude_reason, updated_by)
    values (v_code, btrim(p_rule ->> 'name'), p_rule ->> 'description', coalesce((p_rule ->> 'priority')::int, 500), coalesce(p_rule ->> 'status', 'active'),
        nullif(p_rule ->> 'bank_account_id', '')::uuid, coalesce(p_rule ->> 'direction', 'any'), v_action, v_type,
        coalesce((p_rule ->> 'amount_tolerance')::numeric, 0), coalesce((p_rule ->> 'amount_tolerance_pct')::numeric, 0),
        coalesce((p_rule ->> 'date_window_days')::int, 3), coalesce(p_rule ->> 'reference_mode', 'ignore'),
        nullif(p_rule ->> 'keyword_operator', ''), nullif(p_rule ->> 'keyword_value', ''), v_src, v_vt,
        case when v_action = 'exclude' then coalesce(nullif(p_rule ->> 'exclude_reason', ''), 'other') end, auth.uid())
    returning recon_rule_id into v_id;
  else
    update bank_recon_rules set name = btrim(p_rule ->> 'name'), description = p_rule ->> 'description',
        priority = coalesce((p_rule ->> 'priority')::int, priority), status = coalesce(p_rule ->> 'status', status),
        bank_account_id = nullif(p_rule ->> 'bank_account_id', '')::uuid, direction = coalesce(p_rule ->> 'direction', 'any'),
        action = v_action, match_type = v_type, amount_tolerance = coalesce((p_rule ->> 'amount_tolerance')::numeric, 0),
        amount_tolerance_pct = coalesce((p_rule ->> 'amount_tolerance_pct')::numeric, 0),
        date_window_days = coalesce((p_rule ->> 'date_window_days')::int, 3), reference_mode = coalesce(p_rule ->> 'reference_mode', 'ignore'),
        keyword_operator = nullif(p_rule ->> 'keyword_operator', ''), keyword_value = nullif(p_rule ->> 'keyword_value', ''),
        book_source_types = v_src, book_voucher_types = v_vt,
        exclude_reason = case when v_action = 'exclude' then coalesce(nullif(p_rule ->> 'exclude_reason', ''), 'other') end,
        version = version + 1, updated_at = now(), updated_by = auth.uid()
     where recon_rule_id = v_id;
    if not found then raise exception 'Rule not found'; end if;
  end if;
  return v_id;
end $$;

