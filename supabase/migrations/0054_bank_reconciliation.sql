-- "Match with books" button: tries the match rules only (never books anything new)
create or replace function run_bank_reconciliation(p_bank_account_id uuid default null) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare t record; v_res jsonb; v_n int := 0; v_rec int := 0; v_sug int := 0; v_exc int := 0; v_draft boolean;
begin
  if not has_bankcod_write() then raise exception 'Not authorized to reconcile'; end if;
  for t in select bank_txn_id, (match_status = 'partial' and matched_entity = 'journal_rule') as has_draft from bank_transactions
            where recon_status in ('unreconciled', 'suggested') and (p_bank_account_id is null or bank_account_id = p_bank_account_id)
              and (match_status = 'unmatched' or (match_status = 'partial' and matched_entity = 'journal_rule'))
            order by txn_date, created_at loop
    v_n := v_n + 1;
    v_draft := t.has_draft;
    if v_draft then perform br_cancel_rule_draft(t.bank_txn_id); end if;
    v_res := br_apply_rules_to_txn(t.bank_txn_id);
    if v_res ? 'reconciled' then v_rec := v_rec + 1;
    elsif v_res ? 'suggested' then v_sug := v_sug + 1;
    elsif v_res ? 'excluded' then v_exc := v_exc + 1;
    elsif v_draft then perform jr_process_bank_txn(t.bank_txn_id);   -- nothing in the books: put the rule's draft back
    end if;
  end loop;
  return jsonb_build_object('checked', v_n, 'reconciled', v_rec, 'suggested', v_sug, 'excluded', v_exc);
end $$;

