-- A book entry posted after the statement was imported (a settlement reconciled later, a payment entered late) finds its bank line.
create or replace function trg_voucher_posted_recon() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
declare ln record; t record;
begin
  begin
    if new.status = 'posted' and old.status is distinct from 'posted' and coalesce(new.source_type, '') not in ('bank_txn', 'reversal') then
      for ln in select vl.ledger_id, vl.debit, vl.credit from voucher_lines vl
                 where vl.voucher_id = new.voucher_id and vl.ledger_id in (select ledger_id from bank_accounts where ledger_id is not null) loop
        for t in select b.bank_txn_id from bank_transactions b join bank_accounts a on a.bank_account_id = b.bank_account_id
                  where a.ledger_id = ln.ledger_id and b.recon_status in ('unreconciled', 'suggested')
                    and (b.match_status = 'unmatched' or (b.match_status = 'partial' and b.matched_entity = 'journal_rule'))
                    and b.type = case when ln.debit > 0 then 'credit' else 'debit' end
                    and abs(b.amount - greatest(ln.debit, ln.credit)) <= 1 and abs(b.txn_date - new.voucher_date) <= 15 loop
          perform br_apply_rules_to_txn(t.bank_txn_id);
        end loop;
      end loop;
    end if;
  exception when others then
    null;   -- reconciliation must never block posting
  end;
  return new;
end $$;
drop trigger if exists trg_voucher_posted_recon on vouchers;
create trigger trg_voucher_posted_recon after update of status on vouchers
  for each row execute function trg_voucher_posted_recon();
revoke execute on function trg_voucher_posted_recon() from public, anon, authenticated;

