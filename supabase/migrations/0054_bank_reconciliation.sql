-- "Not a match": keep it out of future proposals and let the Rule Book book it as a fresh entry
create or replace function br_reject_suggestion(p_suggestion uuid, p_book_it boolean default true) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare s bank_recon_suggestions%rowtype; v_left int; v_res jsonb;
begin
  if not has_bankcod_write() then raise exception 'Not authorized to reconcile'; end if;
  select * into s from bank_recon_suggestions where suggestion_id = p_suggestion and status = 'pending';
  if not found then raise exception 'This suggestion is no longer available'; end if;
  update bank_recon_suggestions set status = 'rejected', decided_by = auth.uid(), decided_at = now() where suggestion_id = p_suggestion;
  select count(*) into v_left from bank_recon_suggestions where bank_txn_id = s.bank_txn_id and status = 'pending';
  if v_left = 0 then
    update bank_transactions set recon_status = 'unreconciled' where bank_txn_id = s.bank_txn_id and recon_status = 'suggested';
    if p_book_it then v_res := jr_process_bank_txn(s.bank_txn_id); end if;
  end if;
  return jsonb_build_object('rejected', true, 'remaining', v_left, 'result', v_res);
end $$;

-- Book a missing entry straight from a statement line (e.g. a payment nobody had recorded).
create or replace function br_book_txn(p_txn uuid, p_ledger uuid, p_narration text default null) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  t bank_transactions%rowtype; v_bank uuid; v_period uuid; v_vt uuid; v_prefix text; v_no text; v_vid uuid; v_line uuid;
begin
  if not has_accounting_write() then raise exception 'Not authorized to post vouchers'; end if;
  select * into t from bank_transactions where bank_txn_id = p_txn;
  if not found then raise exception 'Statement line not found'; end if;
  if t.recon_status = 'reconciled' then raise exception 'This line is already reconciled'; end if;
  v_bank := br_bank_ledger_of(t.bank_account_id);
  if v_bank is null then raise exception 'This bank account has no ledger'; end if;
  if p_ledger = v_bank then raise exception 'Choose the other side of the entry, not the bank itself'; end if;
  if not exists (select 1 from ledgers where ledger_id = p_ledger and status = 'active') then raise exception 'Choose an active account'; end if;
  select accounting_period_id into v_period from accounting_periods where t.txn_date between start_date and end_date and status = 'open' limit 1;
  if v_period is null then raise exception 'No open accounting period covers %', t.txn_date; end if;
  select voucher_type_id, numbering_prefix into v_vt, v_prefix from voucher_types where code = case when t.type = 'credit' then 'RECEIPT' else 'PAYMENT' end;
  v_no := v_prefix || '-' || to_char(t.txn_date, 'YYMM') || '-' || lpad(nextval('journal_voucher_seq')::text, 6, '0');

  -- a previous draft from the rules for this line is replaced by this explicit entry
  perform br_cancel_rule_draft(p_txn);
  perform br_unlink(p_txn);
  update bank_recon_suggestions set status = 'withdrawn' where bank_txn_id = p_txn and status = 'pending';

  insert into vouchers (voucher_type_id, voucher_no, voucher_date, accounting_period_id, status, source_type, source_id, narration, total_debit, total_credit, created_by)
  values (v_vt, v_no, t.txn_date, v_period, 'draft', 'bank_txn', t.bank_txn_id, coalesce(nullif(p_narration, ''), t.reference, 'Bank entry'), t.amount, t.amount, auth.uid())
  returning voucher_id into v_vid;
  insert into voucher_lines (voucher_id, ledger_id, debit, credit, reference_type, reference_id, narration) values
    (v_vid, case when t.type = 'credit' then v_bank else p_ledger end, t.amount, 0, 'bank_txn', t.bank_txn_id, t.reference),
    (v_vid, case when t.type = 'credit' then p_ledger else v_bank end, 0, t.amount, 'bank_txn', t.bank_txn_id, t.reference);
  update vouchers set status = 'posted', approved_by = auth.uid() where voucher_id = v_vid;
  update bank_transactions set matched_entity = 'journal_rule', matched_reference_id = v_vid, match_status = 'matched' where bank_txn_id = p_txn;
  perform br_link_rule_voucher(p_txn, v_vid);
  return jsonb_build_object('voucher_id', v_vid, 'voucher_no', v_no);
end $$;

